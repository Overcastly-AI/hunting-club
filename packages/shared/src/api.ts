// Club API wire format: request bodies that aren't plain entity inputs, and the JSON
// shapes that differ from the stored entities. The app, web admin and the Lambda API
// all import these, so a field is named once. Entity bodies (stands, members, …) use
// the Create/Update schemas in club.ts directly.
