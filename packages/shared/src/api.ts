// Club API wire format: request bodies that aren't plain entity inputs, and the JSON
// shapes that differ from the stored entities. The app, web admin and the Lambda API
// all import these, so a field is named once. Entity bodies (stands, members, …) use
// the Create/Update schemas in club.ts directly.
import { z } from 'zod';
import {
  ClubCreateSchema,
  ClubSchema,
  ClubSecretSchema,
  MemberJoinSchema,
  MemberSchema,
  type Subscription,
  ZOOM_RANGE_ORDERED,
  boundsSchema,
  zoomRangeOrdered,
} from './club';
import { SubscriptionStatusSchema, isEntitledStatus } from './enums';
import {
  CHANNEL_KEY_BYTES,
  idSchema,
  inviteTokenSchema,
  planIdSchema,
  timestampSchema,
} from './fields';
import type { ClubApiError } from './enums';
import { BASEMAP_IDS, DOWNLOAD_LIMITS, type BasemapId } from './maps';

/** POST /clubs: a new club with the caller as its first admin. */
export const ClubCreateRequestSchema = z.strictObject({
  club: ClubCreateSchema,
  admin: MemberJoinSchema,
});
export type ClubCreateRequest = z.input<typeof ClubCreateRequestSchema>;

/** POST /invites/redeem: the token from the Club QR code plus the joining profile. */
export const RedeemInviteRequestSchema = MemberJoinSchema.extend({ token: inviteTokenSchema });
export type RedeemInviteRequest = z.input<typeof RedeemInviteRequestSchema>;

/** Bytes encoded by a (valid, padded) base64 string; no Buffer, so it runs in the app too. */
const base64ByteLength = (s: string) => (s.length / 4) * 3 - (s.match(/=+$/)?.[0].length ?? 0);

/** Channel keys travel as standard base64 in JSON. */
export const channelKeyBase64Schema = z
  .base64()
  .refine((s) => base64ByteLength(s) === CHANNEL_KEY_BYTES, {
    message: `channel key must be ${CHANNEL_KEY_BYTES} bytes`,
  });

/** PUT /clubs/:clubId/secret: a new radio key generated by the admin's app. */
export const ClubSecretPutRequestSchema = z.strictObject({ channelKey: channelKeyBase64Schema });
export type ClubSecretPutRequest = z.input<typeof ClubSecretPutRequestSchema>;

/** The club secret as JSON (the key in base64). */
export const ClubSecretResponseSchema = ClubSecretSchema.extend({
  channelKey: channelKeyBase64Schema,
});
export type ClubSecretResponse = z.infer<typeof ClubSecretResponseSchema>;

/** POST /clubs/:clubId/checkout: which plan the admin is buying. */
export const CheckoutRequestSchema = z.strictObject({ planId: planIdSchema });
export type CheckoutRequest = z.input<typeof CheckoutRequestSchema>;
export const CheckoutResponseSchema = z.object({
  /** Stripe-hosted Checkout page to redirect to. */
  url: z.url({ protocol: /^https$/ }),
});
export type CheckoutResponse = z.infer<typeof CheckoutResponseSchema>;

/** Every error response body. */
export interface ApiErrorBody {
  error: { code: ClubApiError; message: string };
}

/** GET /me/clubs: each club the caller belongs to, with their membership. */
export const MyClubSchema = z.object({ club: ClubSchema, membership: MemberSchema });
export type MyClub = z.infer<typeof MyClubSchema>;

/**
 * Days club features stay open after the paid-through date (SPEC "When a
 * subscription lapses"). PLACEHOLDER until the owner picks the grace period.
 */
export const ENTITLEMENT_GRACE_DAYS = 14;

/**
 * GET /clubs/:clubId/entitlement (any member): whether club features are open and
 * until when. Phones cache it so club features keep working offline.
 */
export const EntitlementSchema = z.object({
  clubId: idSchema,
  status: SubscriptionStatusSchema.optional(),
  paidThrough: timestampSchema.optional(),
  /** Club features are open until this moment; absent = closed. */
  featuresUntil: timestampSchema.optional(),
});
export type Entitlement = z.infer<typeof EntitlementSchema>;

/** The one rule turning a subscription into an entitlement (used by the API). */
export function entitlementFor(
  clubId: string,
  subscription: Pick<Subscription, 'status' | 'paidThrough'> | undefined,
): Entitlement {
  if (!subscription) return { clubId };
  const { status, paidThrough } = subscription;
  const base = { clubId, status, ...(paidThrough ? { paidThrough } : {}) };
  if (!paidThrough || !isEntitledStatus(status)) return base;
  const until = Date.parse(paidThrough) + ENTITLEMENT_GRACE_DAYS * 24 * 60 * 60 * 1000;
  return { ...base, featuresUntil: new Date(until).toISOString() };
}

const basemapIdSchema = z.enum(BASEMAP_IDS as [BasemapId, ...BasemapId[]]);

/** POST /clubs/:clubId/map-packs (admin): build a pack of the club's property for one basemap. */
export const MapPackRequestSchema = z
  .strictObject({
    basemap: basemapIdSchema,
    /** Map zooms (512 px based); defaults cover overview to the deepest USGS level. */
    minZoom: z
      .number()
      .int()
      .min(DOWNLOAD_LIMITS.minZoom)
      .max(DOWNLOAD_LIMITS.maxZoom)
      .default(DOWNLOAD_LIMITS.minZoom),
    maxZoom: z
      .number()
      .int()
      .min(DOWNLOAD_LIMITS.minZoom)
      .max(DOWNLOAD_LIMITS.maxZoom)
      .default(DOWNLOAD_LIMITS.maxZoom),
  })
  .refine(zoomRangeOrdered, ZOOM_RANGE_ORDERED);
export type MapPackRequest = z.input<typeof MapPackRequestSchema>;

/** What the map-pack builder Lambda is asked to do (the API's async invoke payload). */
export const MapPackBuildSchema = z
  .strictObject({
    clubId: idSchema,
    packId: idSchema,
    basemap: basemapIdSchema,
    bounds: boundsSchema,
    minZoom: z.number().int(),
    maxZoom: z.number().int(),
  })
  .refine(zoomRangeOrdered, ZOOM_RANGE_ORDERED);
export type MapPackBuild = z.infer<typeof MapPackBuildSchema>;

/** 202 answer: the pack is being built; it appears in GET map-packs when done. */
export const MapPackRequestResponseSchema = z.object({
  packId: idSchema,
  tiles: z.number().int().min(0),
  bytes: z.number().int().min(0),
});
export type MapPackRequestResponse = z.infer<typeof MapPackRequestResponseSchema>;
