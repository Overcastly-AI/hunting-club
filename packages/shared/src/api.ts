import {
  ClubCreateSchema,
  ClubSchema,
  ClubSecretSchema,
  MemberJoinSchema,
  MemberSchema,
  type Subscription,
  SubscriptionSchema,
  ZOOM_RANGE_ORDERED,
  billingIntervalSchema,
  boundsSchema,
  zoomRangeOrdered,
} from './club';
import { SubscriptionStatusSchema, isEntitledStatus } from './enums';
import {
  CHANNEL_KEY_BYTES,
  idSchema,
  inviteTokenSchema,
  planIdSchema,
  timestampSchema,
} from './fields';
import type { ClubApiError } from './enums';
import { BASEMAP_IDS, DOWNLOAD_LIMITS, type BasemapId } from './maps';
import { CLUB_PRICING } from './pricing';

/** POST /clubs: a new club with the caller as its first admin. */
export const ClubCreateRequestSchema = z.strictObject({
  club: ClubCreateSchema,
  admin: MemberJoinSchema,
});
export type ClubCreateRequest = z.input<typeof ClubCreateRequestSchema>;

/** POST /invites/redeem: the token from the Club QR code plus the joining profile. */
export const RedeemInviteRequestSchema = MemberJoinSchema.extend({ token: inviteTokenSchema });
export type RedeemInviteRequest = z.input<typeof RedeemInviteRequestSchema>;

/** Bytes encoded by a (valid, padded) base64 string; no Buffer, so it runs in the app too. */
const base64ByteLength = (s: string) => (s.length / 4) * 3 - (s.match(/=+$/)?.[0].length ?? 0);

/** Channel keys travel as standard base64 in JSON. */
export const channelKeyBase64Schema = z
  .base64()
  .refine((s) => base64ByteLength(s) === CHANNEL_KEY_BYTES, {
    message: `channel key must be ${CHANNEL_KEY_BYTES} bytes`,
  });

/** PUT /clubs/:clubId/secret: a new radio key generated by the admin's app. */
export const ClubSecretPutRequestSchema = z.strictObject({ channelKey: channelKeyBase64Schema });
export type ClubSecretPutRequest = z.input<typeof ClubSecretPutRequestSchema>;

/** The club secret as JSON (the key in base64). */
export const ClubSecretResponseSchema = ClubSecretSchema.extend({
  channelKey: channelKeyBase64Schema,
});
export type ClubSecretResponse = z.infer<typeof ClubSecretResponseSchema>;

/** POST /clubs/:clubId/checkout: which plan the admin is buying. */
export const CheckoutRequestSchema = z.strictObject({
  planId: planIdSchema,
  /** Yearly unless chosen otherwise (CLUB_PRICING.defaultInterval). */
  interval: billingIntervalSchema.default(CLUB_PRICING.defaultInterval),
});
export type CheckoutRequest = z.input<typeof CheckoutRequestSchema>;

/** Stripe Price id per plan and billing interval (the club API's STRIPE_PRICES config). */
export const StripePricesSchema = z.record(
  planIdSchema,
  z.partialRecord(billingIntervalSchema, z.string().min(1)),
);
export type StripePrices = z.infer<typeof StripePricesSchema>;
/** A Stripe-hosted page to redirect to (Checkout, or the customer portal). */
export const StripeRedirectSchema = z.object({ url: z.url({ protocol: /^https$/ }) });
export const CheckoutResponseSchema = StripeRedirectSchema;
export type CheckoutResponse = z.infer<typeof CheckoutResponseSchema>;
/** POST /clubs/{id}/billing-portal: Stripe's customer portal (change or cancel the plan). */
export const BillingPortalResponseSchema = StripeRedirectSchema;
export type BillingPortalResponse = z.infer<typeof BillingPortalResponseSchema>;

